function withRahmenplanSection(items, section, extra = {}) {
  return items.map((item) => ({ ...item, section, ...extra }));
}

// Liste der Positionen für einen Beruf; integrative Positionen haben section
// "gemeinsam" und zusätzlich integrativ: true
function getRahmenplan(beruf) {
  const name = beruf || "";
  let specific = null;
  if (/fachinformatiker/i.test(name)) {
    const fachrichtung = Object.keys(RAHMENPLAN_FACHRICHTUNG).find((key) => name.includes(key));
    specific = [...RAHMENPLAN_FI, ...(fachrichtung ? RAHMENPLAN_FACHRICHTUNG[fachrichtung] : [])];
  } else if (/it-system-elektroniker/i.test(name)) {
    specific = RAHMENPLAN_ITSE;
  } else if (/digitalisierungsmanagement/i.test(name)) {
    specific = RAHMENPLAN_DIGIMAN;
  } else if (/it-system-management/i.test(name)) {
    specific = RAHMENPLAN_ITSM;
  }
  if (!specific) {
    return [];
  }
  return [
    ...withRahmenplanSection(RAHMENPLAN_GEMEINSAM, "gemeinsam"),
    ...withRahmenplanSection(specific, "beruf"),
    ...withRahmenplanSection(RAHMENPLAN_INTEGRATIV, "gemeinsam", { integrativ: true }),
  ];
}

function escapeRahmenplanKeyword(text) {
  return text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

// Schlüsselwort muss am Wortanfang stehen ("konfigur" trifft "konfiguriert",
// "netzwerk" trifft "Netzwerkkabel", aber "rest" nicht "Interesse")
function rahmenplanMatcher(keywords) {
  const pattern = keywords.map(escapeRahmenplanKeyword).join("|");
  return new RegExp(`(?:^|[^a-z0-9äöüß])(?:${pattern})`, "i");
}

function analyzeRahmenplan(weeks, beruf) {
  const items = getRahmenplan(beruf);
  const matchers = items.map((item) => rahmenplanMatcher(item.keywords));
  const stats = items.map(() => ({ hits: 0, weeks: new Set() }));

  for (const week of weeks || []) {
    for (const day of week.days || []) {
      if ((day.kind !== "betrieb" && day.kind !== "schule") || !day.content) {
        continue;
      }
      const text = day.content.toLowerCase();
      matchers.forEach((matcher, index) => {
        if (matcher.test(text)) {
          stats[index].hits += 1;
          stats[index].weeks.add(week.kw);
        }
      });
    }
  }

  return items.map((item, index) => ({
    id: item.id,
    title: item.title,
    section: item.section,
    ...(item.integrativ ? { integrativ: true } : {}),
    hits: stats[index].hits,
    weeks: [...stats[index].weeks].sort((a, b) => a - b),
  }));
}
